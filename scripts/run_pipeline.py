def selection_fingerprint(dispatchable):
    """Hashes of what determines a run's output besides the simulation.

    records: the dispatched records (content and file) and the raw tables
    their experimental values come from; code: the analysis library and the
    pipeline scripts.  run_campaign.py reruns an output when either changes.
    """
    import hashlib
    import json
    rec = hashlib.sha256()
    for fpath, doc, _entry in sorted(dispatchable, key=lambda x: (str(x[0]), json.dumps(
            x[1], sort_keys=True, default=str))):
        rec.update(str(fpath).encode())
        rec.update(json.dumps({k: v for k, v in doc.items() if k != "_record_file"},
                              sort_keys=True, default=str).encode())
        raw = os.path.join(_PROJECT_ROOT, "hepdata_raw/records", f"ins{doc.get('inspire_id')}",
                           f"HEPData-ins{doc.get('inspire_id')}-v{doc.get('version')}-yaml",
                           str(doc.get('hepdata_file')))
        if os.path.isfile(raw):
            with open(raw, 'rb') as fh:
                rec.update(hashlib.sha256(fh.read()).digest())
    code = hashlib.sha256()
    paths = sorted(os.path.join(_PROJECT_ROOT, "analysis", f)
                   for f in os.listdir(os.path.join(_PROJECT_ROOT, "analysis")) if f.endswith(".py"))
    paths += [os.path.join(_PROJECT_ROOT, "scripts", f) for f in ("run_pipeline.py", "compute_flow_vn.py")]
    for p in paths:
        code.update(os.path.basename(p).encode())
        with open(p, 'rb') as fh:
            code.update(fh.read())
    return {"records": rec.hexdigest()[:16], "code": code.hexdigest()[:16],
            "n_records": len(dispatchable)}


def load_config():
    """Load the local simulation path mappings (config/sim_paths.yaml).

    The file is machine-specific and not tracked; without it the tracked
    example (placeholders) is read, so --sim 2d/3d need --sim-path /
    --sim-3d-path.  Simulation packages (--sim-package) need no config.
    """
    path = CONFIG_PATH if os.path.exists(CONFIG_PATH) else CONFIG_EXAMPLE
    with open(path) as f:
        return yaml.safe_load(f) or {}


def group_records(records_iter):
    """Group (file_path, doc) pairs by (reaction, energy_gev).

    Returns: dict {(reaction, energy_str): [(file_path, doc), ...]}
    """
    groups = {}
    for fpath, doc in records_iter:
        cs = doc.get("collision_system", {})
        reaction = cs.get("reaction", "?")
        energy = str(cs.get("energy_gev", "?"))
        key = (reaction, energy)
        groups.setdefault(key, []).append((fpath, doc))
    return groups


def _normalize_reaction(reaction):
    """Map full HEPData reaction strings to abbreviated config keys."""
    upp = reaction.upper()
    for prefix, abbr in [
        ("AU AU", "Au Au"),
        ("PB PB", "Pb Pb"),
        ("P PB", "p Pb"),
        ("XE XE", "Xe Xe"),
        ("AU+AU", "Au Au"),
        ("NE-NE", "Ne-Ne"),
        ("P+P", "p p"),
        ("RU+RU", "Ru Ru"),
        ("RU RU", "Ru Ru"),
        ("RURU", "Ru Ru"),
        ("ZR+ZR", "Zr Zr"),
        ("ZR ZR", "Zr Zr"),
        ("ZRZR", "Zr Zr"),
    ]:
        if upp.startswith(prefix):
            return abbr
    return reaction


def _det_matches(det, det_match):
    """True if a per-record detector override applies to this record.

    ``det_match is None`` (bare spec) matches every record.  Otherwise the
    record's centrality-estimator detector/name must contain the spec or
    vice versa, so that e.g. ``Octagon`` matches an estimator recorded as
    ``{'detector': 'Octagon'}`` or ``{'name': 'octagon multiplicity'}``.
    """
    if det_match is None:
        return True
    return bool(det) and (det_match in det or det in det_match)


def _record_matches(rec, spec, fpath=None):
    """True if a per-record override spec names this record.

    Unlike _det_matches (which is about the centrality DETECTOR), this also
    accepts a collaboration, a source-file or a record-file identifier,
    because some overrides are naturally keyed that way -- e.g.
    `--diff-bins-override <file fragment>=...` targets one record file.
    Checked against: estimator detector, estimator name, inspire_id,
    hepdata_file, collision_system.reaction, and the record's own file path.

    A "key#N" suffix additionally requires the manifest's pinned doc_index
    to equal N, which is how an override targets ONE doc of a multi-doc
    file (all docs of one table share a single HDF5 label key, so an
    override matching several of them would collide).
    """
    if spec is None:
        return True
    spec = spec.lower()
    if '#' in spec:
        key_s, _, idx_s = spec.partition('#')
        try:
            want_idx = int(idx_s)
        except ValueError:
            return False
        if rec.get('_doc_index') != want_idx:
            return False
        spec = key_s.strip()
        if not spec:
            return True
    est = ((rec.get('centrality') or {}).get('estimator') or {})
    hay = [
        str(est.get('detector') or ''),
        str(est.get('name') or ''),
        str(rec.get('inspire_id') or ''),
        str(rec.get('hepdata_file') or ''),
        str((rec.get('collision_system') or {}).get('reaction') or ''),
        str(fpath or ''),
    ]
    return any(spec in h.lower() for h in hay if h)


def _get_sim_path(cfg, sim_type, reaction, energy, fallback=True):
    """Look up simulation data path for a collision system.

    sim_type: '2d' or '3d'
    Falls back to AuAu 200 GeV as proxy when fallback=True.
    """
    norm = _normalize_reaction(reaction)
    paths = cfg.get(sim_type, {}).get(norm, {})
    # Try both exact energy and rounded (config keys are int strings like "200")
    energy_keys = [str(energy), str(int(float(energy)))]
    for ek in energy_keys:
        p = paths.get(ek, None)
        if p is not None:
            break
    if p is None and fallback and sim_type in ("2d", "3d"):
        if sim_type == "2d":
            p = (cfg.get("2d", {}).get("Au Au", {})
                 .get("200", None))
            if p:
                print(f"  (fallback 2d: using AuAu 200 GeV proxy)")

        elif sim_type == "3d":
            p = (cfg.get("3d", {}).get("Au Au", {})
                 .get("200", None))
            if p:
                print(f"  (fallback 3d: using AuAu 200 GeV proxy)")
    return p


def _get_cent_anchor(cfg, reaction, energy):
    """Look up a per-collision-system centrality anchor in config.

    Reads the optional top-level ``cent_anchors`` mapping, keyed by
    "<Reaction> <energy>" (e.g. "Au Au 200").  Returns the anchor spec
    (anything resolve_anchor accepts) or None.  CLI --cent-anchor overrides.
    """
    norm = _normalize_reaction(reaction)
    anchors = cfg.get('cent_anchors', {}) or {}
    energy_str = str(energy)
    for key in (f"{norm} {energy_str}", f"{reaction} {energy_str}",
                f"{norm} {int(float(energy))}"):
        if key in anchors:
            return anchors[key]
    return None


