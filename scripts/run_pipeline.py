def run_block_jackknife(compute_fn, n_events, n_blocks=20):
    """Block jackknife for a combined compute function.

    compute_fn(event_mask) → flat array of all observables.

    Returns: (theta_hat, errors, covariance)
    """
    mask_all = np.ones(n_events, dtype=bool)
    theta_hat = compute_fn(mask_all)

    n_obs = len(theta_hat)
    blocks = jackknife_blocks(n_events, min(n_blocks, n_events))
    n_b = len(blocks)

    theta_i = np.zeros((n_b, n_obs), dtype=np.float64)
    for i, mask in enumerate(blocks):
        vals = compute_fn(mask)
        bad = ~np.isfinite(vals)
        # Also catch unphysical values > 1e6 (catastrophic cancellation
        # from empty pT/cent bins in JK blocks with marginal statistics)
        bad |= np.abs(vals) > 1e6
        if bad.any():
            n_bad = np.sum(bad)
            vals[bad] = theta_hat[bad]
            print(f"    JK block {i}: {n_bad}/{n_obs} bad values (NaN/inf/unphysical) — replaced with full-sample estimate")
        theta_i[i] = vals

    theta_mean = np.mean(theta_i, axis=0)
    diff = theta_i - theta_mean
    cov = (n_b - 1) / n_b * np.dot(diff.T, diff)
    bias = (n_b - 1) * (theta_mean - theta_hat)
    corr = theta_hat - bias
    errors = np.sqrt(np.maximum(np.diag(cov), 0))
    run_block_jackknife.last = (theta_hat, theta_i)     # for --save-jackknife-replicates
    return corr, errors, cov


def harm_major_stack(per_bin_outputs):
    """Stack per-bin ``[v_1..v_N]`` results into HARMONIC-MAJOR order.

    The differential extraction everywhere reads index
    ``(harm - 1) * n_bins + bin``, i.e. all bins of harmonic 1, then all
    bins of harmonic 2, and so on.  A per-bin core returns one row per bin
    containing every harmonic, so concatenating those rows gives BIN-major
    order and silently reads the wrong slot for every bin after the first.

    Kept as a named function so the layout contract is directly testable.
    """
    arr = np.atleast_2d(np.stack([np.asarray(r).ravel()
                                 for r in per_bin_outputs]))
    return arr.T.ravel()


